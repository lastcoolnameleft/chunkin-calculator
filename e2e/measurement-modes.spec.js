const { test, expect } = require('@playwright/test');

test('GPS event creation, capture, shots, export and spectator maps need no stations', async ({ page, context, request }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.grantPermissions(['geolocation']);
  await context.setGeolocation({ latitude: 39.1, longitude: -76.9, accuracy: 3 });
  await page.goto('/');
  await page.getByLabel('How will you measure shots?').selectOption('gps');
  await expect(page.locator('#newEventBaseline')).toBeHidden();
  await page.getByLabel('Event Name', { exact: true }).fill('GPS Field Day');
  await page.locator('#newEventUnit').selectOption('m');
  await page.getByRole('button', { name: 'Create Event', exact: true }).click();
  await expect(page.locator('#eventSummaryName')).toHaveText('GPS Field Day');
  await expect(page.locator('#setupCard')).toBeHidden();
  await expect(page.locator('#angA')).toBeHidden();
  await expect(page.locator('#bearingA')).toBeHidden();
  await expect(page.locator('#trebDist')).toBeHidden();
  await page.locator('#trebName').fill('GPS Launcher');
  await page.getByRole('button', { name: 'Capture GPS at launch location', exact: true }).click();
  await expect(page.locator('#launchLat')).toHaveValue('39.1');
  await expect(page.locator('#launchStatus')).toContainText('±3 m');
  await page.getByRole('button', { name: 'Add trebuchet', exact: true }).click();
  await expect(page.locator('#trebBody')).toContainText('GPS Launcher');
  await page.getByRole('tab', { name: 'Log a Shot', exact: true }).click();
  await page.locator('#trebSelect').selectOption({ label: 'GPS Launcher' });
  await page.locator('#label').fill('GPS round');
  await context.setGeolocation({ latitude: 39.1005, longitude: -76.9, accuracy: 5 });
  await page.getByRole('button', { name: 'Capture GPS at landing location', exact: true }).click();
  await expect(page.locator('#landingStatus')).toContainText('±5 m');
  const eventId = new URL(page.url()).pathname.split('/').pop();
  expect(await (await request.get(`/api/events/${eventId}/shots`)).json()).toEqual([]);
  await page.getByRole('button', { name: 'Add shot', exact: true }).click();
  await expect(page.locator('#latestDistance')).toHaveText('55.6 m');
  await page.screenshot({ path: testInfo.outputPath('gps-event.png'), fullPage: true });
  await expect(page.locator('#shotBody')).toContainText('GPS locations');
  await expect(page.locator('#shotBody')).toContainText('±3 m');
  await expect(page.locator('#shotBody')).toContainText('±5 m');
  await page.getByRole('tab', { name: 'Visualization', exact: true }).click();
  await expect(page.locator('#mapNotice')).toContainText('GPS positions');
  await expect(page.locator('.event-map-station')).toHaveCount(0);
  await expect(page.locator('.event-map-impact')).toHaveCount(1);
  await expect(page.locator('#btnSchematicView')).toBeHidden();
  const shots = await (await request.get(`/api/events/${eventId}/shots`)).json();
  expect(shots[0].angA).toBeNull();
  expect(shots[0].launchGps.accuracy).toBe(3);
  expect(shots[0].landingGps.accuracy).toBe(5);
  await page.getByRole('tab', { name: 'Shot History', exact: true }).click();
  await page.getByRole('button', { name: 'Show CSV', exact: false }).click();
  await expect(page.locator('#csvBox')).toHaveValue(/gps,m/);
  await expect(page.locator('#csvBox')).toHaveValue(/39\.1005/);
  await page.reload();
  await expect(page.locator('#latestDistance')).toHaveText('55.6 m');
  await page.goto(`/event/${eventId}/spectator`);
  await expect(page.locator('#latestDistance')).toHaveText('55.6 m');
  await expect(page.locator('.editor-only:visible')).toHaveCount(0);
  await expect(page.locator('.event-map-station')).toHaveCount(0);
  expect(errors).toEqual([]);
});

